#!/usr/bin/env python

"""BPP command line."""

import argparse
from pathlib import Path

from .common import RAW_HELP_FORMATTER


ANALYSES = ("a00", "a01", "a10", "a11", "msc-i", "msc-m")

EPILOG = r"""
Examples
--------
# A00: fixed species assignments and fixed tree
$ ipyrad2 bpp -d assembly.hdf5 -t species.nwk -i IMAP.txt -g MINMAP.txt -N 1000 -L 100 --analysis A00
# A01: infer the species tree
$ ipyrad2 bpp -d assembly.hdf5 -t species.nwk -i IMAP.txt -g MINMAP.txt -N 1000 -L 100 --analysis A01 --species-model-prior 1
# A10: infer species delimitation on a guide tree
$ ipyrad2 bpp -d assembly.hdf5 -t species.nwk -i IMAP.txt -g MINMAP.txt -N 1000 -L 100 --analysis A10 --delimitation-proposal 1 2 1
# A11: jointly infer delimitation and the species tree
$ ipyrad2 bpp -d assembly.hdf5 -t species.nwk -i IMAP.txt -g MINMAP.txt -N 1000 -L 100 --analysis A11 --species-model-prior 3
# MSC-I: fixed extended-Newick network with introgression annotations
$ ipyrad2 bpp -d assembly.hdf5 -t msci.nwk -i IMAP.txt -g MINMAP.txt -N 1000 -L 100 --analysis MSC-I --phi-prior 1 1
# MSC-M: fixed tree with directional migration bands
$ ipyrad2 bpp -d assembly.hdf5 -t species.nwk -i IMAP.txt -g MINMAP.txt -N 1000 -L 100 --analysis MSC-M --migration A,B --w-prior 2 200

See docs/analyses/bpp-msc-draft.md for parameter syntax and compatibility. The Recipes section will add real-data runs.
"""



def _casefold(value: str) -> str:
    """Normalize case-insensitive CLI choices."""
    return value.casefold()


def _uppercase(value: str) -> str:
    """Normalize case-insensitive substitution-model choices."""
    return value.upper()


def _setup_bpp_subparser(
    subparsers: argparse._SubParsersAction,
    header: str = None,
) -> None:
    """Add the ``ipyrad2 bpp`` subcommand parser."""
    tool = subparsers.add_parser(
        "bpp",
        description=header,
        help="Stage one BPP analysis from sequence HDF5 data and optionally run BPP.",
        epilog=EPILOG,
        formatter_class=RAW_HELP_FORMATTER,
        add_help=False,
    )

    inputs = tool.add_argument_group("Input and output")
    inputs.add_argument(
        "-d", "--data", metavar="PATH", type=Path, required=True,
        help="Assembly HDF5 file generated by ipyrad2.",
    )
    inputs.add_argument(
        "-t", "--tree", metavar="NEWICK|PATH", required=True,
        help="Guide tree as Newick text or a tree-file path.",
    )
    inputs.add_argument(
        "-i", "--imap", metavar="PATH", type=Path, required=True,
        help="Sample-to-population mapping file.",
    )
    inputs.add_argument(
        "-g", "--minmap", metavar="PATH", type=Path, required=True,
        help="Minimum population coverage mapping file.",
    )
    inputs.add_argument(
        "-N", "--max-loci", metavar="INT", type=int, required=True,
        help="Maximum number of loci to sample.",
    )
    inputs.add_argument(
        "-L", "--min-length", metavar="INT", type=int, required=True,
        help="Minimum retained locus length in base pairs.",
    )
    inputs.add_argument(
        "-o", "--out", metavar="PATH", type=Path, default="output-bpp",
        help="Output directory. [default=output-bpp]",
    )
    inputs.add_argument(
        "-n", "--name", metavar="STR", default="bpp",
        help="Output filename prefix. [default=bpp]",
    )

    analysis = tool.add_argument_group("Analysis model")
    analysis.add_argument(
        "--analysis", metavar="MODE", type=_casefold, choices=ANALYSES, default="a00",
        help="BPP mode: A00, A01, A10, A11, MSC-I, or MSC-M. [default=A00]",
    )
    analysis.add_argument(
        "--migration", metavar="SOURCE,TARGET", action="append",
        help="MSC-M migration pair; repeat for multiple bands.",
    )
    analysis.add_argument(
        "--species-model-prior", metavar="INT", type=int, choices=(0, 1, 2, 3),
        help="Prior code for sampled species models. [default=1 when used]",
    )
    analysis.add_argument(
        "--delimitation-proposal", metavar="TOKEN", nargs="+",
        help="A10/A11 rjMCMC proposal: `0 EPSILON` or `1 ALPHA M`.",
    )
    analysis.add_argument(
        "--constraint-file", metavar="PATH", type=Path,
        help="A01/A11 topology constraints using IMAP population names.",
    )

    models = tool.add_argument_group("Evolutionary models and priors")
    models.add_argument(
        "--theta-prior", metavar="TOKEN", nargs="+",
        help="Theta prior specification. [default=invgamma 3 0.002]",
    )
    models.add_argument(
        "--tau-prior", metavar=("DIST", "A", "B"), nargs=3,
        help="Root-age prior. [default=invgamma 3 0.03]",
    )
    models.add_argument(
        "--phi-prior", metavar=("A", "B"), nargs=2, type=float, default=(1.0, 1.0),
        help="MSC-I beta prior on introgression probabilities. [default=1 1]",
    )
    models.add_argument(
        "--w-prior", metavar=("A", "B"), nargs=2, type=float, default=(2.0, 200.0),
        help="MSC-M gamma prior on migration rates. [default=2 200]",
    )
    models.add_argument(
        "--substitution-model", metavar="MODEL", type=_uppercase,
        choices=("JC69", "K80", "F81", "HKY", "T92", "TN93", "F84", "GTR"),
        default="JC69", help="DNA substitution model. [default=JC69]",
    )
    models.add_argument(
        "--alpha-prior", metavar=("A", "B", "NCAT"), nargs=3,
        help="Enable gamma-distributed among-site rates.",
    )
    models.add_argument(
        "--locus-rate", metavar="TOKEN", nargs="+",
        help="Among-locus rate model. [default=0, equal rates]",
    )
    models.add_argument(
        "--clock", metavar="TOKEN", nargs="+",
        help="Molecular clock model. [default=1, strict clock]",
    )
    models.add_argument(
        "--theta-model", metavar="MODEL", type=_casefold,
        choices=("linked-none", "linked-all", "linked-inner", "linked-msci", "linked-mscm"),
        default="linked-none", help="Population-size linkage model. [default=linked-none]",
    )
    models.add_argument(
        "--clean-data", action="store_true",
        help="Remove alignment sites containing ambiguity characters.",
    )

    runtime = tool.add_argument_group("MCMC and execution")
    runtime.add_argument(
        "--burnin", metavar="INT", type=int, default=10000,
        help="Burn-in iterations used for automatic finetuning. [default=10000]",
    )
    runtime.add_argument(
        "--samplefreq", metavar="INT", type=int, default=10,
        help="Iterations between retained MCMC samples. [default=10]",
    )
    runtime.add_argument(
        "--nsample", metavar="INT", type=int, default=100000,
        help="Number of retained MCMC samples. [default=100000]",
    )
    runtime.add_argument(
        "--threads", metavar="INT", nargs="+", type=int,
        help="BPP threads as `N` or `N START STEP`.",
    )
    runtime.add_argument(
        "--locus-seed", metavar="NONE|INT",
        help="Seed for locus subsampling; `none` uses random sampling.",
    )
    runtime.add_argument(
        "--mcmc-seed", metavar="NONE|INT",
        help="Seed for BPP MCMC; `none` uses system entropy.",
    )
    runtime.add_argument(
        "--checkpoint", metavar="INT", nargs="+", type=int,
        help="First checkpoint iteration and optional repeat interval.",
    )
    runtime.add_argument(
        "--bpp-binary", metavar="PATH", type=Path,
        help="BPP 4.8.7 or newer executable.",
    )

    output = tool.add_argument_group("Additional output options")
    output.add_argument(
        "--print-locus-rates", action="store_true",
        help="Write sampled locus rates to the MCMC output.",
    )
    output.add_argument(
        "--print-gene-trees", action="store_true",
        help="Write per-locus gene trees; output can be large.",
    )
    output.add_argument(
        "--print-substitution-parameters", action="store_true",
        help="Write sampled substitution parameters.",
    )
    output.add_argument(
        "--write-only", action="store_true",
        help="Write BPP inputs without resolving or running a binary.",
    )
    output.add_argument(
        "-f", "--force", action="store_true",
        help="Overwrite outputs with identical names.",
    )

    logging = tool.add_argument_group("Logging")
    logging.add_argument(
        "-l", "--log-level", metavar="LEVEL", default="INFO",
        help="Logging threshold. [default=INFO]",
    )
    logging.add_argument(
        "-h", "--help", action="help",
        help="Show this help message and exit.",
    )
